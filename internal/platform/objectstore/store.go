// Package objectstore wraps the S3-compatible bucket used for uploads and media artifacts.
// Browser traffic never passes through the application process (开发技术规范 §2.1 / §6).
package objectstore

import (
	"bytes"
	"context"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/minio/minio-go/v7"
	"github.com/minio/minio-go/v7/pkg/credentials"
	"github.com/yejie/voidxotv/internal/platform/config"
)

const (
	// PartSize matches the reference implementation (8 MiB per part).
	PartSize = int64(8 * 1024 * 1024)
	// MaxParts caps presigned part URLs; SigV4 presigning must stay under 7 days.
	MaxParts     = 10000
	PartURLTTL   = 15 * time.Minute
	MaxGetURLTTL = 7 * 24 * time.Hour
	PlaybackTTL  = 30 * time.Minute
)

// Store owns one bucket and both low-level and ordinary S3 clients.
type Store struct {
	client         *minio.Client
	publicClient   *minio.Client
	core           *minio.Core
	bucket         string
	region         string
	publicEndpoint string
	publicRead     bool
}

func New(cfg config.Config) (*Store, error) {
	if cfg.S3Endpoint == "" || cfg.S3Bucket == "" || cfg.S3AccessKey == "" || cfg.S3SecretKey == "" {
		return nil, fmt.Errorf("objectstore: S3 endpoint, bucket and credentials are required")
	}
	endpoint := trimEndpoint(cfg.S3Endpoint)
	opts := &minio.Options{
		Creds:  credentials.NewStaticV4(cfg.S3AccessKey, cfg.S3SecretKey, ""),
		Secure: strings.HasPrefix(cfg.S3Endpoint, "https://"),
		Region: cfg.S3Region,
	}
	client, err := minio.New(endpoint, opts)
	if err != nil {
		return nil, fmt.Errorf("objectstore: create client: %w", err)
	}

	// Signatures are bound to the host, so URLs handed to browsers must be signed
	// against the public endpoint (CDN in production), not the internal one.
	publicEndpoint := strings.TrimRight(cfg.S3PublicEndpoint, "/")
	if publicEndpoint == "" {
		publicEndpoint = strings.TrimRight(cfg.S3Endpoint, "/")
	}
	publicClient := client
	if trimEndpoint(publicEndpoint) != endpoint {
		publicOpts := *opts
		publicOpts.Secure = strings.HasPrefix(publicEndpoint, "https://")
		publicClient, err = minio.New(trimEndpoint(publicEndpoint), &publicOpts)
		if err != nil {
			return nil, fmt.Errorf("objectstore: create public client: %w", err)
		}
	}
	return &Store{
		client:         client,
		publicClient:   publicClient,
		core:           &minio.Core{Client: client},
		bucket:         cfg.S3Bucket,
		region:         cfg.S3Region,
		publicEndpoint: publicEndpoint,
		publicRead:     cfg.S3PublicRead,
	}, nil
}

func trimEndpoint(raw string) string {
	value := strings.TrimPrefix(strings.TrimPrefix(raw, "https://"), "http://")
	return strings.TrimRight(value, "/")
}

// EnsureBucket creates the dev bucket if it does not exist (production buckets are provisioned externally).
func (s *Store) EnsureBucket(ctx context.Context) error {
	exists, err := s.client.BucketExists(ctx, s.bucket)
	if err != nil {
		return fmt.Errorf("objectstore: bucket lookup: %w", err)
	}
	if !exists {
		if err := s.client.MakeBucket(ctx, s.bucket, minio.MakeBucketOptions{Region: s.region}); err != nil {
			return fmt.Errorf("objectstore: create bucket: %w", err)
		}
	}
	return nil
}

// SourceKey is generated by the server; client filenames never participate in the key.
func SourceKey(ownerID int64) (string, error) {
	buf := make([]byte, 16)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return fmt.Sprintf("uploads/%d/%s/source", ownerID, base64.RawURLEncoding.EncodeToString(buf)), nil
}

func (s *Store) NewMultipart(ctx context.Context, key, contentType string) (string, error) {
	uploadID, err := s.core.NewMultipartUpload(ctx, s.bucket, key, minio.PutObjectOptions{ContentType: contentType})
	if err != nil {
		return "", fmt.Errorf("objectstore: create multipart: %w", err)
	}
	return uploadID, nil
}

func (s *Store) PresignPart(ctx context.Context, key, uploadID string, part int) (string, error) {
	values := url.Values{
		"uploadId":   []string{uploadID},
		"partNumber": []string{strconv.Itoa(part)},
	}
	signed, err := s.client.Presign(ctx, http.MethodPut, s.bucket, key, PartURLTTL, values)
	if err != nil {
		return "", fmt.Errorf("objectstore: presign part: %w", err)
	}
	return signed.String(), nil
}

func (s *Store) CompleteMultipart(ctx context.Context, key, uploadID string, parts []minio.CompletePart) error {
	if len(parts) == 0 {
		return fmt.Errorf("objectstore: no parts to complete")
	}
	if _, err := s.core.CompleteMultipartUpload(ctx, s.bucket, key, uploadID, parts, minio.PutObjectOptions{}); err != nil {
		return fmt.Errorf("objectstore: complete multipart: %w", err)
	}
	return nil
}

func (s *Store) Stat(ctx context.Context, key string) (minio.ObjectInfo, error) {
	info, err := s.client.StatObject(ctx, s.bucket, key, minio.StatObjectOptions{})
	if err != nil {
		return info, fmt.Errorf("objectstore: stat: %w", err)
	}
	return info, nil
}

// DownloadToFile streams with a hard size limit; partial files are removed on failure.
func (s *Store) DownloadToFile(ctx context.Context, key, destination string, maxBytes int64) (int64, error) {
	object, err := s.client.GetObject(ctx, s.bucket, key, minio.GetObjectOptions{})
	if err != nil {
		return 0, fmt.Errorf("objectstore: get object: %w", err)
	}
	defer object.Close()

	file, err := os.Create(destination)
	if err != nil {
		return 0, err
	}
	written, copyErr := io.Copy(file, io.LimitReader(object, maxBytes+1))
	closeErr := file.Close()
	if copyErr != nil || closeErr != nil {
		_ = os.Remove(destination)
		return 0, fmt.Errorf("objectstore: download: %v %v", copyErr, closeErr)
	}
	if written > maxBytes {
		_ = os.Remove(destination)
		return 0, fmt.Errorf("objectstore: object exceeds %d bytes", maxBytes)
	}
	return written, nil
}

// UploadFile streams a local artifact into the versioned media prefix.
func (s *Store) UploadFile(ctx context.Context, key, path, contentType, cacheControl string) (int64, error) {
	file, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil {
		return 0, err
	}
	if _, err := s.client.PutObject(ctx, s.bucket, key, file, info.Size(), minio.PutObjectOptions{
		ContentType: contentType, CacheControl: cacheControl,
	}); err != nil {
		return 0, fmt.Errorf("objectstore: put object: %w", err)
	}
	return info.Size(), nil
}

func (s *Store) PutBytes(ctx context.Context, key string, data []byte, contentType, cacheControl string) error {
	_, err := s.client.PutObject(ctx, s.bucket, key, bytes.NewReader(data), int64(len(data)),
		minio.PutObjectOptions{ContentType: contentType, CacheControl: cacheControl})
	return err
}

// Remove deletes a stored object; used when an author removes a gallery image
// or when a gallery transaction rolls back after the object was already written.
func (s *Store) Remove(ctx context.Context, key string) error {
	return s.client.RemoveObject(ctx, s.bucket, key, minio.RemoveObjectOptions{})
}

func (s *Store) PresignGet(ctx context.Context, key string, ttl time.Duration) (string, error) {
	if ttl <= 0 || ttl > MaxGetURLTTL {
		ttl = PlaybackTTL
	}
	signed, err := s.publicClient.PresignedGetObject(ctx, s.bucket, key, ttl, url.Values{})
	if err != nil {
		return "", fmt.Errorf("objectstore: presign get: %w", err)
	}
	return signed.String(), nil
}

// PresignDownload 生成带下载文件名的签名地址：浏览器按 attachment 保存，
// 不会把原图直接在页面里打开。原图只在用户点「下载原图」时走这条路径。
func (s *Store) PresignDownload(ctx context.Context, key, filename string, ttl time.Duration) (string, error) {
	if ttl <= 0 || ttl > MaxGetURLTTL {
		ttl = PlaybackTTL
	}
	params := url.Values{}
	params.Set("response-content-disposition",
		fmt.Sprintf("attachment; filename*=UTF-8''%s", url.PathEscape(filename)))
	signed, err := s.publicClient.PresignedGetObject(ctx, s.bucket, key, ttl, params)
	if err != nil {
		return "", fmt.Errorf("objectstore: presign download: %w", err)
	}
	return signed.String(), nil
}

// MediaURL returns the browser-facing address for a media object: a stable CDN
// path when the bucket is public-read, otherwise a short-lived presigned GET
// (same policy as playback URLs). Feed galleries and the publish-page preview
// both use this, so an image never 403s just because public read is disabled.
func (s *Store) MediaURL(ctx context.Context, key string) (string, error) {
	if s.publicRead {
		return s.PublicURL(key), nil
	}
	return s.PresignGet(ctx, key, PlaybackTTL)
}

// PublicURL builds a CDN-style path URL without any credential in the query string.
func (s *Store) PublicURL(key string) string {
	segments := strings.Split(strings.TrimPrefix(key, "/"), "/")
	for i := range segments {
		segments[i] = url.PathEscape(segments[i])
	}
	return s.publicEndpoint + "/" + url.PathEscape(s.bucket) + "/" + strings.Join(segments, "/")
}

// GetBytes reads small text artifacts (playlists) only; media bytes never enter the app process.
func (s *Store) GetBytes(ctx context.Context, key string, maxBytes int64) ([]byte, error) {
	object, err := s.client.GetObject(ctx, s.bucket, key, minio.GetObjectOptions{})
	if err != nil {
		return nil, fmt.Errorf("objectstore: get text object: %w", err)
	}
	defer object.Close()
	data, err := io.ReadAll(io.LimitReader(object, maxBytes+1))
	if err != nil {
		return nil, fmt.Errorf("objectstore: read text object: %w", err)
	}
	if int64(len(data)) > maxBytes {
		return nil, fmt.Errorf("objectstore: text object exceeds %d bytes", maxBytes)
	}
	return data, nil
}
